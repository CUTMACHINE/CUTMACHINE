"""GR16 -- docs/roadmap/GRADE-RESOLVE-2026-10.md (DEC46). Writes
src/ResolveContrastTable.cc and tests/fixtures/resolve_primaries/
contrast_held_out.txt from the measurement of 25 October 2026.

The source is outside the repository: 1 072 grades posed in DaVinci Resolve
Studio 21.1.0.17 (colour management v2, DaVinci WG / Intermediate, HDR 1000,
colour-space-aware tools and the contrast S-curve on, Lum Mix 0), one
contrast and one pivot each, and the diagonal of the 65-point cube Resolve's
ExportLUT gave: one curve y(x) per setting, on DaVinci Intermediate values
x = i / 64. 1 056 of them make the grid (contrast 1.025 to 1.8 by 0.025,
pivot 0 to 1 by 0.05, 0.435, and by 0.025 below 0.3 and above 0.75); the
other 16 were measured off the grid and only check the interpolation. The
contrast 1 is the identity and is added, not measured.

  python3 make_contrast_table.py ~/CUTMACHINE-mesures/gr15-facteurs/table-aware
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SAMPLES = 65


def axis(values):
    """An axis as C++ lines of nine floats, as clang-format packs them."""
    text = [f"{v:.3f}f" for v in values]
    rows = ["    " + ", ".join(text[i:i + 9]) + ","
            for i in range(0, len(text), 9)]
    rows[-1] = rows[-1][:-1] + "};"
    return rows


def main(source):
    source = Path(source)
    cases = {k: tuple(v) for k, v in
             json.loads((source / "cases.json").read_text()).items()}
    grid, held = {}, []
    for line in (source / "diagonals.jsonl").read_text().splitlines():
        row = json.loads(line)
        c, p = cases[row["case"]]
        curve = row["diagonal"]
        assert len(curve) == SAMPLES
        if row["case"].startswith("v_"):
            held.append((c, p, curve))
        else:
            grid[(round(c, 3), round(p, 3))] = curve
    contrasts = sorted({c for c, _ in grid})
    pivots = sorted({p for _, p in grid})
    assert len(grid) == len(contrasts) * len(pivots), "grid has holes"
    for p in pivots:
        grid[(1.0, p)] = [i / (SAMPLES - 1) for i in range(SAMPLES)]
    contrasts = [1.0] + contrasts

    lines = [
        "// Generated by tools/resolve-grade-probe/make_contrast_table.py from",
        "// the measurement of 25 October 2026 (GR16 --",
        "// docs/roadmap/GRADE-RESOLVE-2026-10.md); do not edit by hand.",
        '#include "ResolveContrastTable.h"',
        "",
        "#include <array>",
        "#include <cstdint>",
        "",
        "namespace resolve_contrast_table {",
        "",
        f"const std::array<float, {len(contrasts)}> kContrasts = {{",
        *axis(contrasts),
        f"const std::array<float, {len(pivots)}> kPivots = {{",
        *axis(pivots),
        "// y * 65535, contrast-major, then pivot, then the 65 samples.",
        "// clang-format off",
        f"const std::array<uint16_t, {len(contrasts) * len(pivots) * SAMPLES}> "
        "kCurves = {",
    ]
    for c in contrasts:
        for p in pivots:
            values = [round(min(max(v, 0.0), 1.0) * 65535)
                      for v in grid[(c, p)]]
            for start in range(0, SAMPLES, 11):
                lines.append("    " + ",".join(str(v) for v in
                                                values[start:start + 11]) + ",")
    lines += ["};", "// clang-format on", "",
              "}  // namespace resolve_contrast_table", ""]
    (ROOT / "src" / "ResolveContrastTable.cc").write_text("\n".join(lines))

    fixture = [
        "# GR16 -- written by tools/resolve-grade-probe/make_contrast_table.py:",
        "# contrast, pivot, then Resolve's 65 values, for settings measured",
        "# off the grid of src/ResolveContrastTable.cc.",
    ]
    for c, p, curve in sorted(held):
        fixture.append(f"{c:g} {p:g} " + " ".join(f"{v:.6f}" for v in curve))
    (ROOT / "tests" / "fixtures" / "resolve_primaries" /
     "contrast_held_out.txt").write_text("\n".join(fixture) + "\n")
    print(len(contrasts), "contrastes,", len(pivots), "pivots,", len(held),
          "cas de contrôle")


if __name__ == "__main__":
    main(sys.argv[1])
