#pragma once

// GR16 -- docs/roadmap/GRADE-RESOLVE-2026-10.md (DEC46). The contrast of a
// DaVinci Resolve 21.1 node, as color.resolve_primaries renders it.
//
// Above 1, with Resolve's default "Use S-curve for contrast", the contrast
// is an S-curve that keeps black and white where they are; no formula was
// found for it (25 October 2026: neither a sigmoid, nor a fixed blend of
// the identity and the straight contrast, nor two Bezier halves, nor the
// power halves of the public "S-Curve Contrast" DCTL). It is therefore a
// table measured in Resolve: ResolveContrastTable.cc, generated by
// tools/resolve-grade-probe/make_contrast_table.py from 1 056 cubes, one per
// stored contrast (1.025 to 1.8 by 0.025) and pivot (33, finer at the
// ends), in a project with the colour-space-aware tools on -- the setting
// of the author's projects. Each curve is y(x) on DaVinci Intermediate values
// x = i / 64. Between them, a cubic through the four nearest contrasts and
// the four nearest pivots, and Catmull-Rom along x: within 0.12 of a
// 10-bit code of 16 settings measured off the grid for a pivot from 0.25 to
// 0.75 (95 % of the contrasts the author set in 14 150 grades), 0.5 to 1.6 at
// the far pivots, 4.8 at worst (1.5 about 0.06).
//
// With the aware tools, Resolve applies its plain contrast in HLG: the
// value x to linear light, divided by 12 (HLG's peak at 12 times reference
// white), HLG-encoded; the contrast acts on that code about the stored
// pivot; back the same way. Measured to 0.07 of a code where the code
// stays within [0, 1]. Without them, the same plain contrast acts on the
// node's values directly, so the table read through HLG gives it too:
// ResolveContrastCurve does either.
//
// Portable: plain C++, compiled into the engine on every host.

#include <array>
#include <cstddef>
#include <cstdint>

namespace resolve_contrast_table {
extern const std::array<float, 33> kContrasts;
extern const std::array<float, 33> kPivots;
extern const std::array<uint16_t, size_t{33} * 33 * 65> kCurves;
}  // namespace resolve_contrast_table

inline constexpr int32_t kResolveContrastSamples = 65;
// The S-curve table ends at this stored contrast; above it, nothing is
// measured and the stage refuses the contrast.
inline constexpr float kResolveContrastTableMost = 1.8f;

// The aware S-curve at DaVinci Intermediate value x, for a stored contrast
// in [1, kResolveContrastTableMost] and pivot in [0, 1], from the table.
// x outside [0, 1] goes on along the end slopes.
float ResolveAwareSCurve(float contrast, float pivot, float x);

// The HLG code of a value, for the aware contrast: DaVinci Intermediate to
// linear, divided by 12, BT.2100 HLG; a negative value keeps its sign.
float ResolveContrastToHlg(float diValue);
float ResolveContrastFromHlg(float hlgCode);

// The curve a color.resolve_primaries stage applies for its contrast, as
// kResolveContrastSamples values on [0, end] of the domain the contrast
// acts in -- the HLG code with the aware tools, the node's value without
// them -- to be read by ApplyResolveContrastCurve; `end` is the HLG code of
// the value 1 in both. False when the contrast changes nothing (a stored
// 1). Straight (a contrast up to 1, or the S-curve switched off):
// (max(u - 0.0005, 0) - pivot) * slope + pivot, slope the contrast up to 1
// and 1 / (2 - contrast) above. S-curve: the table, through HLG without the
// aware tools.
bool ResolveContrastCurve(float contrast, float pivot, bool aware, bool sCurve,
                          std::array<float, 65>& samples, float& end);

// Reads such a curve at u: Catmull-Rom between samples, and the end slopes
// past the ends. shader.metal's resolveContrastCurve is the same.
float ApplyResolveContrastCurve(const float* samples, float end, float u);
