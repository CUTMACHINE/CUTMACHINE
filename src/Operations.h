// PL1 -- ROADMAP.md. One intervention, one undo step. An agent that chains
// twenty operations used to leave twenty history entries: undoing its
// intervention took twenty Undo, and nothing said where it began.
//
// A batch applies its members in order on one candidate document and is
// refused whole when any member is: no member's effect survives a refusal
// further on. The members are kept as they were applied -- generated IDs
// and exact states included -- so that redo and a journal read back replay
// them identically; the inverse is the members' inverses, last first,
// under the same label.
//
// Members are operations, written in full in the journal, rather than the
// strings of JSON the first draft (codex/ai-edit-plans, 5 September) kept:
// a script reading the journal sees an intervention's structure instead of
// escaped text. That draft also carried the whole canonical document the
// batch expected, twice per entry; a batch in the journal is replayed in
// the order of its own history, so a stale document is a question for the
// surface that prepares one (PL2), not for every undo step.
//
// Not nested: a batch inside a batch is refused. EditLog::GroupSince
// flattens one instead when it folds an intervention.
struct BatchOperation {
    std::string label;
    std::vector<Operation> operations;
};

// The first draft's bound. It keeps a single undo step, and the journal
