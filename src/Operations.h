// R3 -- docs/roadmap/REEL-2026-09.md. A clip's constant speed, as an exact
// fraction (ClipSpeed.h holds the rule it implies). The inverse is the
// previous speed, which makes apply -> undo byte-exact.
//
// Criterion 2 of the ticket: a speed on a linked clip is set on every
// member of its group, never on one of them, so picture and sound cannot
// drift apart without anybody saying so -- the export stretches the sound
// with atempo, pitch kept (ClipSpeed.h). Every member therefore always
// carries the same speed, which is why the inverse needs no per-member
// state: setting the previous speed on the same clip restores the group. A
// video clip in no group -- the case the film measured actually used, since
// none of its rushes' sound was kept -- slows down on its own.
//
// Criterion 4 (11 October 2026) -- or a ramp: keys of speed over the clip's
// own time, `speed` then left at 1/1. A clip's speed is one or the other,
// so the operation sets both at once and its inverse carries both: setting
// a ramp on a clip at 1/2 and undoing it gives back the 1/2. A ramp is
// picture only (ClipSpeed.h), so it never touches a link group.
struct SetClipSpeedOperation {
    Ulid clip_id;
    EffectParamValue speed{1, 1};
    std::vector<ClipKeyframe> ramp;
};

