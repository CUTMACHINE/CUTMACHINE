// FC3 -- docs/roadmap/FILMCRAFT-2026-10.md. Adapted from FilmCraft
// crates/edit/src/lib.rs `rate_stretch` (MIT OR Apache-2.0, commit
// 09aaf9b). Gives a clip a new timeline `duration` while it keeps reading
// the same source range, so its constant speed becomes span / duration,
// computed as an exact fraction. FilmCraft stores that quotient as an f64;
// here a speed that ClipSpeedIsValid does not accept (terms past
// kMaxClipSpeedTerm) is refused, never approximated. `edge` is the one that
// moves: Tail keeps the head where it is, Head keeps the tail.
//
// Like set_clip_speed, a linked clip takes its whole link group with it,
// so picture and sound keep one speed (REEL-2026-09 R3); every member must
// then have the anchor's duration and speed, or the group would leave with
// several. A ramp, a freeze, a caption and a motion clip are refused. Without
// `ripple`, nothing ripples: a stretch that runs into the next clip is
// refused as an overlap, one that shortens leaves a gap (the behaviour of
// trim_clip).
//
// DEC40 -- docs/roadmap/FILMCRAFT-2026-10.md. With `ripple`, the stretch
// ripples as Resolve's does in its Trim mode (Resolve 21.1 manual, p. 1219):
// each member keeps its head where it is, whichever edge is dragged, as a
// ripple_trim of a head keeps it, and every other clip that starts at or
// after a member's old end on that member's track moves by the change of
// length. `sync_track_ids` are the other tracks that follow, as for
// RippleTrimOperation: time added opens at the anchor's old end, time taken
// out is the stretch [new end, old end) collapsed through
// CollapseClipThroughRange. A link group with two members on one track is
// refused with ripple: the first member's ripple would move the second.
// Both members come last, after the snapshots, so that the aggregate
// initialisations written before them still read as they did.
struct RateStretchOperation {
    Ulid clip_id;
    TrimEdge edge = TrimEdge::Tail;
    RationalTime duration;
    std::vector<ExactTrackState> exact_track_result;
    bool ripple = false;
    std::vector<Ulid> sync_track_ids;
};

